const RCON = [0x00, 0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36];

function xtime(a: number) {
  return ((a << 1) ^ ((a & 0x80) ? 0x1b : 0)) & 0xff;
}

function mul(a: number, b: number) {
  let p = 0;
  for (let i = 0; i < 8; i++) {
    if (b & 1) p ^= a;
    const hi = a & 0x80;
    a = (a << 1) & 0xff;
    if (hi) a ^= 0x1b;
    b >>= 1;
  }
  return p;
}

function expandKey(key: Uint8Array) {
  if (key.length !== 16) throw new Error("AES-128 key must be 16 bytes");
  const w = new Uint8Array(176);
  w.set(key);
  for (let i = 16, rc = 1; i < 176; i += 4) {
    let a = w[i - 4], b = w[i - 3], c = w[i - 2], d = w[i - 1];
    if (i % 16 === 0) {
      const t = a;
      a = SBOX[b] ^ RCON[rc++];
      b = SBOX[c];
      c = SBOX[d];
      d = SBOX[t];
    }
    w[i] = w[i - 16] ^ a;
    w[i + 1] = w[i - 15] ^ b;
    w[i + 2] = w[i - 14] ^ c;
    w[i + 3] = w[i - 13] ^ d;
  }
  return w;
}

function addRoundKey(s: Uint8Array, rk: Uint8Array, off: number) {
  for (let i = 0; i < 16; i++) s[i] ^= rk[off + i];
}

function subBytes(s: Uint8Array, box: Uint8Array) {
  for (let i = 0; i < 16; i++) s[i] = box[s[i]];
}

function shiftRows(s: Uint8Array) {
  let t = s[1]; s[1] = s[5]; s[5] = s[9]; s[9] = s[13]; s[13] = t;
  t = s[2]; s[2] = s[10]; s[10] = t; t = s[6]; s[6] = s[14]; s[14] = t;
  t = s[15]; s[15] = s[11]; s[11] = s[7]; s[7] = s[3]; s[3] = t;
}

function invShiftRows(s: Uint8Array) {
  let t = s[13]; s[13] = s[9]; s[9] = s[5]; s[5] = s[1]; s[1] = t;
  t = s[2]; s[2] = s[10]; s[10] = t; t = s[6]; s[6] = s[14]; s[14] = t;
  t = s[3]; s[3] = s[7]; s[7] = s[11]; s[11] = s[15]; s[15] = t;
}

function mixColumns(s: Uint8Array) {
  for (let c = 0; c < 4; c++) {
    const i = c * 4;
    const a = s[i], b = s[i + 1], cc = s[i + 2], d = s[i + 3];
    s[i] = xtime(a) ^ xtime(b) ^ b ^ cc ^ d;
    s[i + 1] = a ^ xtime(b) ^ xtime(cc) ^ cc ^ d;
    s[i + 2] = a ^ b ^ xtime(cc) ^ xtime(d) ^ d;
    s[i + 3] = xtime(a) ^ a ^ b ^ cc ^ xtime(d);
  }
}

function invMixColumns(s: Uint8Array) {
  for (let c = 0; c < 4; c++) {
    const i = c * 4;
    const a = s[i], b = s[i + 1], cc = s[i + 2], d = s[i + 3];
    s[i] = mul(a, 14) ^ mul(b, 11) ^ mul(cc, 13) ^ mul(d, 9);
    s[i + 1] = mul(a, 9) ^ mul(b, 14) ^ mul(cc, 11) ^ mul(d, 13);
    s[i + 2] = mul(a, 13) ^ mul(b, 9) ^ mul(cc, 14) ^ mul(d, 11);
    s[i + 3] = mul(a, 11) ^ mul(b, 13) ^ mul(cc, 9) ^ mul(d, 14);
  }
}

export function aes128EncryptBlock(key: Uint8Array, block: Uint8Array): Uint8Array {
  const rk = expandKey(key);
  const s = Uint8Array.from(block);
  addRoundKey(s, rk, 0);
  for (let r = 1; r < 10; r++) {
    subBytes(s, SBOX);
    shiftRows(s);
    mixColumns(s);
    addRoundKey(s, rk, r * 16);
  }
  subBytes(s, SBOX);
  shiftRows(s);
  addRoundKey(s, rk, 160);
  return s;
}

export function aes128DecryptBlock(key: Uint8Array, block: Uint8Array): Uint8Array {
  const rk = expandKey(key);
  const s = Uint8Array.from(block);
  addRoundKey(s, rk, 160);
  for (let r = 9; r >= 1; r--) {
    invShiftRows(s);
    subBytes(s, INV_SBOX);
    addRoundKey(s, rk, r * 16);
    invMixColumns(s);
  }
  invShiftRows(s);
  subBytes(s, INV_SBOX);
  addRoundKey(s, rk, 0);
  return s;
}

export function aesCbcDecryptNoPad(key: Uint8Array, iv: Uint8Array, data: Uint8Array): Uint8Array {
  if (data.length % 16 !== 0) throw new Error("ciphertext length must be a multiple of 16");
  const out = new Uint8Array(data.length);
  let prev = iv;
  for (let i = 0; i < data.length; i += 16) {
    const block = data.subarray(i, i + 16);
    const dec = aes128DecryptBlock(key, block);
    for (let j = 0; j < 16; j++) out[i + j] = dec[j] ^ prev[j];
    prev = block;
  }
  return out;
}

export function aesCbcEncryptNoPad(key: Uint8Array, iv: Uint8Array, data: Uint8Array): Uint8Array {
  if (data.length % 16 !== 0) throw new Error("plaintext length must be a multiple of 16");
  const out = new Uint8Array(data.length);
  let prev = iv;
  for (let i = 0; i < data.length; i += 16) {
    const x = new Uint8Array(16);
    for (let j = 0; j < 16; j++) x[j] = data[i + j] ^ prev[j];
    const enc = aes128EncryptBlock(key, x);
    out.set(enc, i);
    prev = enc;
  }
  return out;
}

function hexEq(a: Uint8Array, hex: string) {
  const want = hex.replace(/\s/g, "").toLowerCase();
  const got = [...a].map((b) => b.toString(16).padStart(2, "0")).join("");
  return got === want;
}

/** NIST AES-128 + CMAC vectors. Throws if this module is wrong. */
export function assertAesCmacSelfCheck() {
  const aesKey = parseHexLoose("000102030405060708090a0b0c0d0e0f");
  const pt = parseHexLoose("00112233445566778899aabbccddeeff");
  const ct = aes128EncryptBlock(aesKey, pt);
  if (!hexEq(ct, "69c4e0d86a7b0430d8cdb78070b4c55a")) throw new Error("AES-128 encrypt self-check failed");
  if (!hexEq(aes128DecryptBlock(aesKey, ct), "00112233445566778899aabbccddeeff")) {
    throw new Error("AES-128 decrypt self-check failed");
  }
  const cmacKey = parseHexLoose("2b7e151628aed2a6abf7158809cf4f3c");
  if (!hexEq(aesCmac(cmacKey, new Uint8Array(0)), "bb1d6929e95937287fa37d129b756746")) {
    throw new Error("AES-CMAC empty self-check failed");
  }
  const m16 = parseHexLoose("6bc1bee22e409f96e93d7e117393172a");
  if (!hexEq(aesCmac(cmacKey, m16), "070a16b46b4d4144f79bdd9dd04a287c")) {
    throw new Error("AES-CMAC 16-byte self-check failed");
  }
}

function parseHexLoose(hex: string) {
  const out = new Uint8Array(hex.length / 2);
  for (let i = 0; i < out.length; i++) out[i] = parseInt(hex.slice(i * 2, i * 2 + 2), 16);
  return out;
}

function dbl(block: Uint8Array): Uint8Array {
  const out = new Uint8Array(16);
  const msb = block[0] & 0x80;
  for (let i = 0; i < 15; i++) out[i] = ((block[i] << 1) | (block[i + 1] >> 7)) & 0xff;
  out[15] = (block[15] << 1) & 0xff;
  if (msb) out[15] ^= 0x87;
  return out;
}

/** AES-128 CMAC (NIST SP 800-38B). */
export function aesCmac(key: Uint8Array, message: Uint8Array): Uint8Array {
  const L = aes128EncryptBlock(key, new Uint8Array(16));
  const k1 = dbl(L);
  const k2 = dbl(k1);
  const complete = message.length > 0 && message.length % 16 === 0;
  const n = message.length === 0 ? 1 : Math.ceil(message.length / 16);
  const last = new Uint8Array(16);
  if (message.length === 0) {
    last[0] = 0x80;
    for (let i = 0; i < 16; i++) last[i] ^= k2[i];
  } else {
    const lastStart = (n - 1) * 16;
    const lastLen = message.length - lastStart;
    last.set(message.subarray(lastStart, lastStart + lastLen));
    if (complete) {
      for (let i = 0; i < 16; i++) last[i] ^= k1[i];
    } else {
      last[lastLen] = 0x80;
      for (let i = 0; i < 16; i++) last[i] ^= k2[i];
    }
  }
  let x = new Uint8Array(16);
  for (let i = 0; i < n - 1; i++) {
    const y = new Uint8Array(16);
    for (let j = 0; j < 16; j++) y[j] = x[j] ^ message[i * 16 + j];
    x = Uint8Array.from(aes128EncryptBlock(key, y));
  }
  const y = new Uint8Array(16);
  for (let i = 0; i < 16; i++) y[i] = x[i] ^ last[i];
  return aes128EncryptBlock(key, y);
}
